"""Full distribution report for a saved `syncopate eval` result.

    python3 scripts/benchmark_report.py results/jamendo_demucs.json > docs/benchmark.md

Reads only the saved JSON (no models are run). Reports what a single
"79% within 300 ms" hides: the pooled error tail, per-song results, how much
of the miss comes from a few catastrophic songs, and what the low-confidence
review flag catches versus how much review work it creates.

Definitions
- line error: |predicted line onset - true line onset|, seconds, as saved.
- late line: line error > 0.3 s (the headline tolerance).
- flagged line: line confidence < FLAG_THRESHOLD (the editor's review flag).
- catastrophic song: fewer than half of its lines within 0.3 s.
Percentiles use linear interpolation over all pooled lines.
"""

from __future__ import annotations

import json
import statistics
import sys

TOL = 0.3
FLAG_THRESHOLD = 0.10


def pct(xs: list[float], p: float) -> float:
    xs = sorted(xs)
    i = (len(xs) - 1) * p
    lo = int(i)
    hi = min(lo + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def fmt_s(x: float) -> str:
    return f"{x * 1000:.0f} ms" if x < 1 else f"{x:.2f} s"


def main(path: str) -> None:
    d = json.load(open(path))
    songs = d["per_song"]
    errs = [e for s in songs for e in s["line_errors"]]
    conf = [c for s in songs for c in s.get("line_confidence", [])]
    n = len(errs)
    late = [e > TOL for e in errs]

    out = [f"# Benchmark distribution: {d['dataset']}", "",
           f"Source: `{path}` (run date {d['date']}, vocal separation: {d.get('vocal_separation', False)}). "
           f"Generated by `scripts/benchmark_report.py` from saved predictions; no model was re-run.", "",
           "## Pooled line-onset error", "",
           f"{len(songs)} songs, {n} lines.", "",
           "| Measure | Value |", "|---|---|",
           f"| Lines within 300 ms | {sum(not x for x in late)}/{n} ({sum(not x for x in late) / n:.1%}) |",
           f"| Lines within 1 s | {sum(e <= 1.0 for e in errs)}/{n} ({sum(e <= 1.0 for e in errs) / n:.1%}) |",
           f"| Median | {fmt_s(statistics.median(errs))} |",
           f"| Mean | {fmt_s(statistics.mean(errs))} |",
           f"| p90 | {fmt_s(pct(errs, 0.90))} |",
           f"| p95 | {fmt_s(pct(errs, 0.95))} |",
           f"| Max | {fmt_s(max(errs))} |",
           "",
           "The median is small and the mean is large: most lines are close, and a minority "
           "are off by tens of seconds. For a live prompter, that tail is what an audience notices.", ""]

    cat = [s for s in songs if sum(e <= TOL for e in s["line_errors"]) / s["lines"] < 0.5]
    rest = [e for s in songs if s not in cat for e in s["line_errors"]]
    cat_lines = sum(s["lines"] for s in cat)
    cat_late = sum(e > TOL for s in cat for e in s["line_errors"])
    out += ["## Where the misses come from", "",
            f"Catastrophic songs (under half their lines within 300 ms): {len(cat)} of {len(songs)}, "
            f"{cat_lines} lines, {cat_late} of the {sum(late)} late lines ({cat_late / max(sum(late), 1):.0%}).", "",
            f"Excluding them, {sum(e <= TOL for e in rest)}/{len(rest)} lines "
            f"({sum(e <= TOL for e in rest) / len(rest):.1%}) are within 300 ms. "
            "That number is shown to explain the failure mode, not as the headline: "
            "those songs are part of the benchmark.", ""]

    out += ["## Per song", "",
            "| Song | Lines | Within 300 ms | Median | Mean | Max |", "|---|---|---|---|---|---|"]
    for s in sorted(songs, key=lambda s: sum(e <= TOL for e in s["line_errors"]) / s["lines"]):
        e = s["line_errors"]
        within = sum(x <= TOL for x in e)
        out.append(f"| {s['song']} | {s['lines']} | {within}/{s['lines']} ({within / s['lines']:.0%}) | "
                   f"{fmt_s(statistics.median(e))} | {fmt_s(statistics.mean(e))} | {fmt_s(max(e))} |")
    out.append("")

    if len(conf) == n:
        flagged = [c < FLAG_THRESHOLD for c in conf]
        tp = sum(f and l for f, l in zip(flagged, late))
        out += ["## Low-confidence review flag", "",
                f"Flag = line confidence below {FLAG_THRESHOLD}. A flagged line is shown to the operator for checking.", "",
                "| Measure | Value |", "|---|---|",
                f"| Late lines caught (recall) | {tp}/{sum(late)} ({tp / sum(late):.1%}) |",
                f"| Flags that were really late (precision) | {tp}/{sum(flagged)} ({tp / max(sum(flagged), 1):.1%}) |",
                f"| Lines flagged (review load) | {sum(flagged)}/{n} ({sum(flagged) / n:.1%}) |",
                f"| Late lines missed by the flag | {sum(late) - tp} |", "",
                "The threshold was chosen on this same 20-song set, so these numbers are optimistic. "
                "They need a held-out set before being quoted as a general property.", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results/jamendo_demucs.json")
